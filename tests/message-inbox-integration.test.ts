/**
 * Real Postgres, the migrated test database (including 0020), two extra connections.
 * Identity columns assign nextval before commit, so a keyset cursor can skip a row that commits later.
 * The inbox trigger locks until commit before nextval, so that interleaving cannot happen.
 */

const RESULT_SCHEMA = { type: 'object', properties: { ok: { type: 'boolean' } }, required: ['ok'] };

function deferred<T = void>() {
  let resolve!: (value: T) => void;
  let reject!: (reason?: unknown) => void;
  const promise = new Promise<T>((res, rej) => {
    resolve = res;
    reject = rej;
  });
  return { promise, resolve, reject };
}

function clients() {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error('DATABASE_URL is not set');
  return [
    postgres(url, { max: 1, prepare: false }),
    postgres(url, { max: 1, prepare: false }),
    postgres(url, { max: 1, prepare: false }),
  ] as const;
}

async function pair() {
  const session = await signIn();
  const from = await createAgent(session.cookie, 'alice');
  const to = await createAgent(session.cookie, 'bob');
  return {
    session,
    from,
    to,
    fromKey: await createKey(session.cookie, from.id),
    toKey: await createKey(session.cookie, to.id),
  };
}

// Interleaves open transactions on separate sessions: real Postgres only (TEST_DATABASE_URL).
describe.runIf(realPostgres)('inbox arrival order versus commit order', () => {
  const open: postgres.Sql[] = [];

  afterEach(async () => {
    await Promise.all(open.splice(0).map((sql) => sql.end({ timeout: 1 })));
  });

  it('an identity keyset skips a row whose lower number commits after a higher one is listed', async () => {
    const [a, b, reader] = clients();
    open.push(a, b, reader);
    await reader`drop table if exists inbox_seq_hazard`;
    await reader`
      create table inbox_seq_hazard (
        id bigint generated by default as identity primary key,
        body text not null
      )
    `;
    const release = deferred();
    const inserted = deferred<string>();
    const earlyTx = a.begin(async (tx) => {
      const rows = await tx`insert into inbox_seq_hazard (body) values ('early') returning id::text`;
      inserted.resolve(rows[0]!.id);
      await release.promise;
    });
    const early = await inserted.promise;
    const late = await b.begin(async (tx) => {
      const rows = await tx`insert into inbox_seq_hazard (body) values ('late') returning id::text`;
      return rows[0]!.id;
    });
    const visible = await reader`select id::text as id, body from inbox_seq_hazard order by id`;
    expect(visible.map((row) => row.body)).toEqual(['late']);
    expect(BigInt(early)).toBeLessThan(BigInt(late));
    const nextPage = await reader`select body from inbox_seq_hazard where id > ${late}::bigint order by id`;
    expect(nextPage).toEqual([]);
    release.resolve();
    await earlyTx;
    const after = await reader`select body from inbox_seq_hazard order by id`;
    expect(after.map((row) => row.body)).toEqual(['early', 'late']);
    await reader`drop table inbox_seq_hazard`;
  });

  it('holds the inbox lock until commit so a later send cannot become visible first', async () => {
    const { session, from, to, toKey } = await pair();
    const [a, b] = clients();
    open.push(a, b);
    const release = deferred();
    const inserted = deferred<string>();
    const earlyTx = a.begin(async (tx) => {
      const rows = await tx`
        insert into messages (workspace_id, from_agent_id, to_agent_id, body)
        values (${session.workspace.id}, ${from.id}, ${to.id}, 'early')
        returning inbox_seq::text
      `;
      inserted.resolve(rows[0]!.inbox_seq);
      await release.promise;
    });
    const earlySeq = await inserted.promise;

    let lateFinished = false;
    const lateTx = b.begin(async (tx) => {
      const rows = await tx`
        insert into messages (workspace_id, from_agent_id, to_agent_id, body)
        values (${session.workspace.id}, ${from.id}, ${to.id}, 'late')
        returning inbox_seq::text
      `;
      lateFinished = true;
      return rows[0]!.inbox_seq as string;
    });
    await new Promise((resolve) => setTimeout(resolve, 300));
    expect(lateFinished).toBe(false);

    const mid = await mcpTool(toKey, 'list_messages', {});
    expect(mid.isError, mid.text).toBe(false);
    expect(mid.payload.messages).toEqual([]);

    release.resolve();
    await earlyTx;
    const lateSeq = await lateTx;
    expect(BigInt(earlySeq)).toBeLessThan(BigInt(lateSeq));

    const page = await mcpTool(toKey, 'list_messages', { limit: 1 });
    expect(page.isError, page.text).toBe(false);
    expect(page.payload.messages.map((message: { body: string }) => message.body)).toEqual(['early']);
    const next = await mcpTool(toKey, 'list_messages', { limit: 1, cursor: page.payload.next_cursor });
    expect(next.payload.messages.map((message: { body: string }) => message.body)).toEqual(['late']);
    expect(next.payload.next_cursor).toBeNull();
  });
});

describe('standalone inbox integration', () => {
  afterEach(() => {
    delete process.env.VALETTO_AGENT_GUESTS;
  });

  it('sends, pages, marks, and repeats over MCP and HTTP, and denies the wrong callers', async () => {
    const owner = await signIn();
    const alice = await createAgent(owner.cookie, 'alice');
    const bob = await createAgent(owner.cookie, 'bob');
    const carol = await createAgent(owner.cookie, 'carol');
    const aliceKey = await createKey(owner.cookie, alice.id);
    const bobKey = await createKey(owner.cookie, bob.id);
    const carolKey = await createKey(owner.cookie, carol.id);
    const other = await signIn();
    const outsider = await createAgent(other.cookie, 'outsider');
    const outsiderKey = await createKey(other.cookie, outsider.id);

    const sent = await mcpTool(aliceKey, 'send_message', { to: 'bob', body: 'shipped the draft' });
    expect(sent.isError, sent.text).toBe(false);
    const second = await mcpTool(aliceKey, 'send_message', { to: 'bob', body: 'and the notes' });
    expect(second.isError, second.text).toBe(false);
    const noticeId = sent.payload.message.id as string;
    const notesId = second.payload.message.id as string;

    const first = await mcpTool(bobKey, 'list_messages', { limit: 1 });
    expect(first.isError, first.text).toBe(false);
    expect(first.payload.messages).toEqual([
      expect.objectContaining({ id: noticeId, body: 'shipped the draft', unread: true, read_at: null, task_id: null }),
    ]);
    expect(first.payload.next_cursor).toEqual(expect.any(String));
    const watermark = first.payload.unread_cursor as string;
    expect(watermark).toEqual(expect.any(String));

    const httpNext = await call(
      listMessagesRoute,
      `http://localhost/api/v1/messages?limit=1&cursor=${encodeURIComponent(first.payload.next_cursor)}`,
      { bearer: bobKey },
    );
    expect(httpNext.status).toBe(200);
    expect(httpNext.data.messages[0]).toMatchObject({ id: notesId, body: 'and the notes', unread: true });
    expect(httpNext.data.unread_cursor).toBe(watermark);
    expect(httpNext.data.next_cursor).toBeNull();

    const marked = await call(markMessagesRoute, 'http://localhost/api/v1/messages/read', {
      bearer: bobKey,
      body: { message_ids: [noticeId] },
    });
    expect(marked.status).toBe(200);
    expect(marked.data.messages[0]).toMatchObject({ id: noticeId, unread: false });
    expect(marked.data.unread_cursor).not.toBe(watermark);
    expect(marked.data.unread_cursor).toEqual(expect.any(String));
    const readAt = marked.data.messages[0].read_at as string;
    const afterFirst = marked.data.unread_cursor as string;

    const again = await mcpTool(bobKey, 'mark_messages_read', { message_ids: [noticeId] });
    expect(again.isError, again.text).toBe(false);
    expect(again.payload.messages[0].read_at).toBe(readAt);
    expect(again.payload.unread_cursor).toBe(afterFirst);

    const unread = await mcpTool(bobKey, 'list_messages', { unread: true });
    expect(unread.payload.messages.map((message: { id: string }) => message.id)).toEqual([notesId]);
    const done = await mcpTool(bobKey, 'mark_messages_read', { message_ids: [notesId] });
    expect(done.payload.unread_cursor).toBeNull();
    const repeated = await mcpTool(bobKey, 'mark_messages_read', { message_ids: [notesId] });
    expect(repeated.payload.messages[0].read_at).toBe(done.payload.messages[0].read_at);

    for (const key of [aliceKey, carolKey, outsiderKey]) {
      const hidden = await mcpTool(key, 'list_messages', {});
      expect(hidden.payload.messages ?? []).toEqual([]);
      const denied = await mcpTool(key, 'mark_messages_read', { message_ids: [noticeId] });
      expect(denied.payload).toMatchObject({ error: 'not_found' });
    }
    const still = await mcpTool(bobKey, 'list_messages', {});
    expect(still.payload.messages.find((message: { id: string }) => message.id === noticeId).read_at).toBe(readAt);

    const noKey = await call(listMessagesRoute, 'http://localhost/api/v1/messages', { cookie: owner.cookie });
    expect(noKey.status).toBe(401);

    process.env.VALETTO_AGENT_GUESTS = '1';
    const handle = `g${crypto.randomUUID().replace(/-/g, '').slice(0, 8)}`;
    expect(
      (
        await call(patchWorkspace, 'http://localhost/api/v1/workspaces/current', {
          method: 'PATCH',
          cookie: owner.cookie,
          body: { handle },
        })
      ).status,
    ).toBe(200);
    const shared = await createAgent(owner.cookie, 'Grok');
    expect(
      (
        await call(postOffer, `http://localhost/api/v1/agents/${shared.id}/offers`, {
          cookie: owner.cookie,
          params: { id: shared.id },
          body: { name: 'draft', description: 'Draft.', result_schema: RESULT_SCHEMA },
        })
      ).status,
    ).toBe(201);
    expect(
      (
        await call(putSharing, `http://localhost/api/v1/agents/${shared.id}/sharing`, {
          method: 'PUT',
          cookie: owner.cookie,
          params: { id: shared.id },
          body: { shared: true },
        })
      ).status,
    ).toBe(200);
    const invite = await call(postInvite, `http://localhost/api/v1/agents/${shared.id}/invites`, {
      cookie: owner.cookie,
      params: { id: shared.id },
      body: { kind: 'agent', offers: ['draft'], approve_on_redeem: true, max_uses: 2 },
    });
    expect(invite.status).toBe(201);
    const redeemed = await call(redeemRoute, 'http://localhost/api/v1/invites/redeem', {
      body: { invite: invite.data.token, name: 'GuestBot' },
      headers: { 'x-forwarded-for': '10.8.8.8' },
    });
    expect(redeemed.status).toBe(201);
    const guestKey = redeemed.data.api_key as string;
    expect((await mcpListTools(guestKey)).map((tool) => tool.name)).not.toContain('list_messages');
    const guestList = await mcpTool(guestKey, 'list_messages', {});
    expect(guestList.payload).toMatchObject({ error: 'insufficient_scope' });
    expect(guestList.text).not.toContain('shipped the draft');
    const guestMark = await mcpTool(guestKey, 'mark_messages_read', { message_ids: [noticeId] });
    expect(guestMark.payload).toMatchObject({ error: 'insufficient_scope' });
    const guestHttp = await call(listMessagesRoute, 'http://localhost/api/v1/messages', { bearer: guestKey });
    expect(guestHttp.status).toBe(403);
    expect(guestHttp.text).not.toContain('shipped the draft');
    const afterGuest = await mcpTool(bobKey, 'list_messages', {});
    expect(afterGuest.payload.messages.find((message: { id: string }) => message.id === noticeId).read_at).toBe(readAt);
  });
});
